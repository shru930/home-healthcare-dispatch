-- Home Healthcare Nurse & Pharmacy Dispatch: relational schema (PostgreSQL 17; also runs on H2 in PostgreSQL mode for tests)

CREATE TABLE patient (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mrn                   VARCHAR(30)  NOT NULL UNIQUE,
    first_name            VARCHAR(80)  NOT NULL,
    last_name             VARCHAR(80)  NOT NULL,
    date_of_birth         DATE         NOT NULL,
    gender                VARCHAR(20),
    phone                 VARCHAR(20)  NOT NULL,
    email                 VARCHAR(120),
    address_line          VARCHAR(200) NOT NULL,
    city                  VARCHAR(80)  NOT NULL,
    postal_code           VARCHAR(12),
    latitude              DOUBLE PRECISION NOT NULL,
    longitude             DOUBLE PRECISION NOT NULL,
    family_contact_name   VARCHAR(120) NOT NULL,
    family_contact_phone  VARCHAR(20)  NOT NULL,
    family_contact_email  VARCHAR(120) NOT NULL,
    surgery_type          VARCHAR(120),
    surgery_date          DATE,
    discharge_date        DATE,
    hospital              VARCHAR(120),
    doctor_name           VARCHAR(120),
    doctor_email          VARCHAR(120),
    status                VARCHAR(30)  NOT NULL,
    created_at            TIMESTAMP    NOT NULL,
    updated_at            TIMESTAMP    NOT NULL
);

CREATE TABLE nurse (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(60)  NOT NULL UNIQUE,
    full_name        VARCHAR(120) NOT NULL,
    phone            VARCHAR(20)  NOT NULL,
    email            VARCHAR(120),
    skills           VARCHAR(200) NOT NULL,
    base_area        VARCHAR(80)  NOT NULL,
    latitude         DOUBLE PRECISION NOT NULL,
    longitude        DOUBLE PRECISION NOT NULL,
    available        BOOLEAN      NOT NULL,
    max_patients     INTEGER      NOT NULL,
    current_patients INTEGER      NOT NULL,
    created_at       TIMESTAMP    NOT NULL
);

CREATE TABLE workflow_instance (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id             BIGINT       NOT NULL REFERENCES patient(id),
    process_instance_key   BIGINT       UNIQUE,
    process_definition_id  VARCHAR(80)  NOT NULL,
    status                 VARCHAR(30)  NOT NULL,
    current_stage          VARCHAR(120) NOT NULL,
    plan_outcome           VARCHAR(40),
    last_error             VARCHAR(500),
    started_at             TIMESTAMP    NOT NULL,
    ended_at               TIMESTAMP
);

CREATE TABLE home_care_plan (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id            BIGINT      NOT NULL REFERENCES patient(id),
    workflow_instance_id  BIGINT      NOT NULL REFERENCES workflow_instance(id),
    start_date            DATE        NOT NULL,
    end_date              DATE        NOT NULL,
    required_skill        VARCHAR(40) NOT NULL,
    status                VARCHAR(30) NOT NULL,
    plan_outcome          VARCHAR(40),
    summary               VARCHAR(1000),
    created_at            TIMESTAMP   NOT NULL
);

CREATE TABLE nurse_assignment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    care_plan_id     BIGINT      NOT NULL REFERENCES home_care_plan(id),
    nurse_id         BIGINT      NOT NULL REFERENCES nurse(id),
    distance_meters  INTEGER,
    travel_seconds   INTEGER,
    distance_source  VARCHAR(30) NOT NULL,
    assignment_mode  VARCHAR(20) NOT NULL,
    note             VARCHAR(300),
    assigned_at      TIMESTAMP   NOT NULL
);

CREATE TABLE home_care_visit (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    care_plan_id  BIGINT      NOT NULL REFERENCES home_care_plan(id),
    day_number    INTEGER     NOT NULL,
    visit_date    DATE        NOT NULL,
    visit_type    VARCHAR(40) NOT NULL,
    nurse_id      BIGINT      REFERENCES nurse(id),
    status        VARCHAR(20) NOT NULL,
    notes         VARCHAR(500),
    completed_at  TIMESTAMP,
    CONSTRAINT uq_visit_day UNIQUE (care_plan_id, day_number),
    CONSTRAINT ck_visit_day CHECK (day_number BETWEEN 1 AND 7)
);

CREATE TABLE health_assessment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id         BIGINT      NOT NULL REFERENCES home_care_visit(id),
    pain_score       INTEGER     NOT NULL,
    temperature      DOUBLE PRECISION NOT NULL,
    wound_redness    BOOLEAN     NOT NULL,
    wound_discharge  BOOLEAN     NOT NULL,
    swelling         BOOLEAN     NOT NULL,
    nurse_notes      VARCHAR(500),
    risk_level       VARCHAR(20) NOT NULL,
    risk_reasons     VARCHAR(500),
    assessed_at      TIMESTAMP   NOT NULL,
    CONSTRAINT ck_pain CHECK (pain_score BETWEEN 0 AND 10)
);

CREATE TABLE risk_intervention (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id     BIGINT      NOT NULL REFERENCES health_assessment(id),
    patient_id        BIGINT      NOT NULL REFERENCES patient(id),
    risk_level        VARCHAR(20) NOT NULL,
    status            VARCHAR(40) NOT NULL,
    escalation_level  VARCHAR(40) NOT NULL,
    doctor_decision   VARCHAR(30),
    notes             VARCHAR(500),
    opened_at         TIMESTAMP   NOT NULL,
    closed_at         TIMESTAMP
);

CREATE TABLE physiotherapy_appointment (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    care_plan_id      BIGINT       NOT NULL REFERENCES home_care_plan(id),
    session_no        INTEGER      NOT NULL,
    day_number        INTEGER      NOT NULL,
    appointment_date  DATE         NOT NULL,
    focus             VARCHAR(120) NOT NULL,
    physiotherapist   VARCHAR(80)  NOT NULL,
    status            VARCHAR(30)  NOT NULL,
    notes             VARCHAR(500),
    CONSTRAINT uq_physio_session UNIQUE (care_plan_id, session_no)
);

CREATE TABLE prescription (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id        BIGINT       NOT NULL REFERENCES patient(id),
    care_plan_id      BIGINT       REFERENCES home_care_plan(id),
    medication        VARCHAR(120) NOT NULL,
    dosage            VARCHAR(80)  NOT NULL,
    quantity          INTEGER      NOT NULL,
    controlled        BOOLEAN      NOT NULL,
    doctor_approved   BOOLEAN      NOT NULL,
    status            VARCHAR(30)  NOT NULL,
    pharmacy          VARCHAR(120),
    status_reason     VARCHAR(300),
    created_at        TIMESTAMP    NOT NULL,
    CONSTRAINT ck_quantity CHECK (quantity > 0)
);

CREATE TABLE pharmacy_stock (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pharmacy    VARCHAR(120) NOT NULL,
    partner     BOOLEAN      NOT NULL,
    medication  VARCHAR(120) NOT NULL,
    quantity    INTEGER      NOT NULL,
    CONSTRAINT uq_stock UNIQUE (pharmacy, medication)
);

CREATE TABLE medication_delivery (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id  BIGINT      NOT NULL REFERENCES prescription(id),
    delivery_ref     VARCHAR(30) NOT NULL UNIQUE,
    pharmacy         VARCHAR(120) NOT NULL,
    courier          VARCHAR(80),
    status           VARCHAR(30) NOT NULL,
    dispatched_at    TIMESTAMP,
    expected_by      TIMESTAMP,
    delivered_at     TIMESTAMP,
    note             VARCHAR(300)
);

CREATE TABLE notification (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id    BIGINT       REFERENCES patient(id),
    channel       VARCHAR(10)  NOT NULL,
    recipient     VARCHAR(120) NOT NULL,
    subject       VARCHAR(200),
    message       VARCHAR(2000) NOT NULL,
    category      VARCHAR(40)  NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    provider_ref  VARCHAR(200) UNIQUE,
    error         VARCHAR(500),
    created_at    TIMESTAMP    NOT NULL
);

CREATE INDEX ix_workflow_patient ON workflow_instance(patient_id);
CREATE INDEX ix_visit_plan ON home_care_visit(care_plan_id);
CREATE INDEX ix_rx_patient ON prescription(patient_id);
CREATE INDEX ix_notification_patient ON notification(patient_id);
CREATE INDEX ix_intervention_patient ON risk_intervention(patient_id);
